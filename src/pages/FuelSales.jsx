// ─── Main Page ─────────────────────────────────────────────────────────────────
export default function FuelSales() {
  const { transactions, deleteTransaction, dateRange } = useApp();
  const [search, setSearch] = useState('');
  const [fuelFilter, setFuelFilter] = useState('All');
  const [payFilter, setPayFilter] = useState('All');
  const [modal, setModal] = useState(null); // 'add' | 'view' | 'delete'
  const [selected, setSelected] = useState(null);
  const [page, setPage] = useState(1);
  const PER_PAGE = 15;

  const filtered = useMemo(() => {
    return transactions.filter(t => {
      const dateOk = t.date >= dateRange.start && t.date <= dateRange.end;
      const searchOk = !search ||
        t.id.toLowerCase().includes(search.toLowerCase()) ||
        t.vehicleNumber?.toLowerCase().includes(search.toLowerCase()) ||
        t.customerName?.toLowerCase().includes(search.toLowerCase());
      const fuelOk = fuelFilter === 'All' || FUEL_LABELS[t.fuelType] === fuelFilter;
      const payOk = payFilter === 'All' || t.paymentMethod === payFilter;
      return dateOk && searchOk && fuelOk && payOk;
    });
  }, [transactions, search, fuelFilter, payFilter, dateRange]);

  const paginated = filtered.slice((page - 1) * PER_PAGE, page * PER_PAGE);
  const totalPages = Math.ceil(filtered.length / PER_PAGE);

  const totalRevenue = filtered.reduce((s, t) => s + t.totalAmount, 0);
  const totalQty = filtered.reduce((s, t) => s + t.quantity, 0);
  const avgTxn = filtered.length > 0 ? totalRevenue / filtered.length : 0;

  return (
    <AppLayout title="Fuel Sales" subtitle="Transaction history and management">
      <div className="space-y-5 animate-fade-in">
        {/* KPIs */}
        <div className="grid grid-cols-2 lg:grid-cols-4 gap-4">
          <KPICard title="Total Transactions" value={filtered.length.toLocaleString('en-IN')} change={0} icon={Hash} iconBg="bg-blue-50" iconColor="text-blue-600" />
          <KPICard title="Total Revenue" value={fmtCurrency(totalRevenue, true)} change={0} icon={IndianRupee} iconBg="bg-emerald-50" iconColor="text-emerald-600" />
          <KPICard title="Total Volume" value={`${fmtNumber(totalQty, 0)} L`} change={0} icon={Fuel} iconBg="bg-slate-100" iconColor="text-slate-600" />
          <KPICard title="Avg. Transaction" value={fmtCurrency(avgTxn, true)} change={0} icon={ShoppingCart} iconBg="bg-violet-50" iconColor="text-violet-600" />
        </div>

        {/* Table */}
        <Card padding={false} className="overflow-hidden">
          {/* Toolbar */}
          <div className="px-5 pt-5 pb-3 flex items-center gap-3 flex-wrap border-b border-slate-100">
            <CardHeader title="Transactions" subtitle={`${filtered.length} records`} icon={ShoppingCart} />
            <div className="flex items-center gap-2 ml-auto flex-wrap">
              <SearchInput value={search} onChange={setSearch} placeholder="Search ID, vehicle..." className="w-48" />
              <select
                value={fuelFilter}
                onChange={e => { setFuelFilter(e.target.value); setPage(1); }}
                className="px-2.5 py-1.5 text-xs border border-slate-200 rounded-lg bg-white text-slate-600 focus:outline-none focus:border-emerald-400"
              >
                {FUEL_FILTER_OPTIONS.map(f => <option key={f}>{f}</option>)}
              </select>
              <select
                value={payFilter}
                onChange={e => { setPayFilter(e.target.value); setPage(1); }}
                className="px-2.5 py-1.5 text-xs border border-slate-200 rounded-lg bg-white text-slate-600 focus:outline-none focus:border-emerald-400"
              >
                {PAYMENT_FILTER_OPTIONS.map(p => <option key={p}>{p}</option>)}
              </select>
              <PrimaryButton size="sm" icon={Plus} onClick={() => setModal('add')}>Add Transaction</PrimaryButton>
            </div>
          </div>

          {/* Table */}
          <div className="overflow-x-auto">
            <table className="w-full text-xs" role="table" aria-label="Fuel transactions table">
              <thead>
                <tr className="bg-slate-50 border-b border-slate-100">
                  {['TXN ID', 'Date & Time', 'Fuel Type', 'Vehicle', 'Qty', 'Unit Price', 'Amount', 'Payment', 'Actions'].map(h => (
                    <th key={h} className="px-4 py-3 text-left font-semibold text-slate-500">{h}</th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {paginated.map((t, i) => (
                  <tr key={t.id} className="border-b border-slate-50 hover:bg-slate-50 transition-colors">
                    <td className="px-4 py-3 font-mono text-slate-600">{t.id}</td>
                    <td className="px-4 py-3 text-slate-500 whitespace-nowrap">{fmtDateTime(t.timestamp)}</td>
                    <td className="px-4 py-3">
                      <span className="flex items-center gap-1.5">
                        <span className="w-2 h-2 rounded-full" style={{ background: FUEL_COLORS[t.fuelType] }} />
                        <span className="text-slate-700 font-medium">{FUEL_LABELS[t.fuelType]}</span>
                      </span>
                    </td>
                    <td className="px-4 py-3 font-mono text-slate-500">{t.vehicleNumber || '—'}</td>
                    <td className="px-4 py-3 font-tabular text-slate-700">{t.quantity.toFixed(1)} {t.unit}</td>
                    <td className="px-4 py-3 font-tabular text-slate-600">₹{t.unitPrice.toFixed(2)}</td>
                    <td className="px-4 py-3 font-tabular font-semibold text-slate-800">{fmtCurrency(t.totalAmount)}</td>
                    <td className="px-4 py-3">
                      <span className={`px-1.5 py-0.5 rounded text-[10px] font-semibold
                        ${t.paymentMethod === 'Cash' ? 'bg-emerald-100 text-emerald-700' :
                          t.paymentMethod === 'UPI' ? 'bg-blue-100 text-blue-700' :
                          t.paymentMethod === 'Card' ? 'bg-violet-100 text-violet-700' :
                          'bg-amber-100 text-amber-700'}`}>
                        {t.paymentMethod}
                      </span>
                    </td>
                    <td className="px-4 py-3">
                      <div className="flex items-center gap-1">
                        <GhostButton size="sm" icon={Eye} onClick={() => { setSelected(t); setModal('view'); }} />
                        {t._manualEntry && (
                          <GhostButton size="sm" onClick={() => { setSelected(t); setModal('delete'); }}>
                            <Trash2 className="w-3.5 h-3.5 text-red-400" />
                          </GhostButton>
                        )}
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          {/* Pagination */}
          <div className="px-5 py-3 bg-slate-50 flex items-center justify-between">
            <p className="text-xs text-slate-400">{filtered.length} transactions · Page {page}/{totalPages}</p>
            <div className="flex gap-1">
              <SecondaryButton size="sm" disabled={page === 1} onClick={() => setPage(p => p - 1)}>Prev</SecondaryButton>
              <SecondaryButton size="sm" disabled={page >= totalPages} onClick={() => setPage(p => p + 1)}>Next</SecondaryButton>
            </div>
          </div>
        </Card>
      </div>

      {/* Modals */}
      <Modal isOpen={modal === 'add'} onClose={() => setModal(null)} title="Add Fuel Transaction" size="lg">
        <TransactionForm onSuccess={() => setModal(null)} onCancel={() => setModal(null)} />
      </Modal>

      <Modal isOpen={modal === 'view'} onClose={() => setModal(null)} title="Transaction Receipt" size="sm">
        <ReceiptModal txn={selected} onClose={() => setModal(null)} />
      </Modal>

      <ConfirmDialog
        isOpen={modal === 'delete'}
        onClose={() => setModal(null)}
        onConfirm={() => { deleteTransaction(selected?.id); setModal(null); }}
        title="Delete Transaction"
        message={`Are you sure you want to delete transaction ${selected?.id}? This action cannot be undone.`}
        confirmLabel="Delete"
        danger
      />
    </AppLayout>
  );
}
