import { useState, useMemo } from 'react';
import AppLayout from '../components/layout/AppLayout';
import { useApp } from '../context/AppContext';
import Card, { CardHeader } from '../components/ui/Card';
import { PrimaryButton, SecondaryButton, DangerButton, GhostButton } from '../components/ui/Buttons';
import Modal from '../components/ui/Modal';
import ConfirmDialog from '../components/ui/ConfirmDialog';
import SearchInput from '../components/ui/SearchInput';
import StatusPill from '../components/ui/StatusPill';
import KPICard from '../components/shared/KPICard';
import TransactionForm from '../components/forms/TransactionForm';
import { fmtCurrency, fmtDateTime, fmtDate, FUEL_LABELS, FUEL_COLORS, fmtNumber } from '../utils/formatters';
import { Plus, Eye, Trash2, Download, Filter, Fuel, IndianRupee, Hash, ShoppingCart, Printer, CheckCircle2 } from 'lucide-react';

